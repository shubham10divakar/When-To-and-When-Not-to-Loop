def validate(paths: Paths | None = None, *, runs: int | None = None) -> dict:
    """E0: mock end-to-end + estimator recovery against the mock's known (p, r, e)."""
    paths = paths or Paths.make(mock=True)
    cfg = load_config("E0_mock")
    if runs:
        cfg["runs_per_cell"] = runs
    run_experiment(cfg, out_root=paths.raw)
    steps, _ = fit.load_experiments([cfg["name"]], paths.raw)
    naive = steps[steps["arm"] == "naive"]
    mk = fit.fit_markov(naive, n_boot=500)
    truth = {k: cfg["client"][k] for k in ("p", "r", "e")}
    res = {}
    for k, v in truth.items():
        lo, hi = mk["wilson"][k]
        res[k] = {"truth": v, "estimate": mk[k], "ci": [lo, hi], "recovered": lo <= v <= hi}
    res["all_recovered"] = all(r["recovered"] for r in res.values() if isinstance(r, dict))
    (paths.processed / "validation_E0.json").write_text(json.dumps(res, indent=2))
    return res


def calibrate(paths: Paths, *, scale: float | None = None, verbose: bool = False, run_experiments: bool = True):
    if run_experiments:
        run(CALIBRATION, paths, scale=scale, verbose=verbose)
    res = fit.fit_all(CALIBRATION, paths.raw, markov_from=["E3_reliability_cal"], coupling_from=["E5_coupling"],
                      n_boot=1000)
    y, j = fit.save_fit(res, paths.processed)
    print(f"fitted parameters -> {y}\nfit report -> {j}")
    return res


def predict_stage(paths: Paths, *, post_hoc: bool = False, n_sim: int = 10_000, regenerate_e9: bool = False):
    f = fit.load_fit(paths.processed)
    e9 = load_config("E9_feasibility")
    if regenerate_e9 or not paths.e9_cells.exists():
        cells = predict.generate_e9_cells(f, constraints=e9["constraints"], summ_every=int(e9.get("summ_every", 5)))
        predict.write_e9_cells(cells, paths.e9_cells)
        print(f"E9 cells ({len(cells)}) -> {paths.e9_cells}")
    out = {}
    for n in PREDICTION:
        df = predict.predict_experiment(_cfg(n, paths), f, n_sim=n_sim, post_hoc=post_hoc, raw_root=paths.raw,
                                        out=paths.processed)
        out[n] = df
        print(f"predictions {n}: {len(df)} cells")
    return out


def prereg_check() -> list[str]:
    """Problems preventing the prediction phase (empty list = OK)."""
    def git(*a):
        return subprocess.run(["git", *a], cwd=REPO_ROOT, capture_output=True, text=True)

    problems = []
    for f_ in ("preregistration/PREREG.md", "preregistration/thresholds.yaml"):
        if git("ls-files", "--error-unmatch", f_).returncode != 0:
            problems.append(f"{f_} is not committed")
    if git("status", "--porcelain", "preregistration", "configs/experiments").stdout.strip():
        problems.append("uncommitted changes under preregistration/ or configs/experiments/")
    if git("rev-parse", "-q", "--verify", f"refs/tags/{PREREG_TAG}").returncode != 0:
        problems.append(f"git tag {PREREG_TAG} does not exist")
    elif git("diff", "--quiet", PREREG_TAG, "HEAD", "--", "preregistration", "configs/experiments").returncode != 0:
        problems.append(f"preregistration/ or configs/experiments/ changed since tag {PREREG_TAG}")
    for n in PREDICTION:
        p = f"data/processed/predictions_{n}.csv"
        if git("ls-files", "--error-unmatch", p).returncode != 0:
            problems.append(f"{p} is not committed (run `make predict` first)")
    return problems


def run_predict(paths: Paths, *, scale: float | None = None, skip_prereg: bool = False, verbose: bool = False):
    if paths.provider:
        missing = [n for n in PREDICTION if not (paths.processed / f"predictions_{n}.csv").exists()]
        if missing and not skip_prereg:
            raise SystemExit(f"run `predict` for this model first (missing predictions: {missing})")
    elif not paths.mock and not skip_prereg:
        problems = prereg_check()
        if problems:
            raise SystemExit("prereg-check failed:\n  - " + "\n  - ".join(problems))
    return run(PREDICTION, paths, scale=scale, verbose=verbose)


def external(paths: Paths, *, verbose: bool = False) -> int:
    from loopbounds.tasks_coding import run_coding_experiment

    cfg = load_config(EXTERNAL)
    if paths.provider:
        cfg = {**cfg, "client": paths.client_spec(int(cfg.get("seed", 0)))}
    if paths.budget_usd is not None:
        cfg["max_spend_usd"] = max(0.0, paths.budget_usd - paths.spent_usd())
    n = run_coding_experiment(cfg, out_root=paths.raw, mock=paths.mock, verbose=verbose)
    print(f"{EXTERNAL}: {n} runs")
    return n


def analyze(paths: Paths, *, l2_runs: int = 100_000) -> dict:
    names = sorted(p.name for p in paths.raw.iterdir() if p.is_dir())
    fit.process(names, paths.raw, paths.processed)
    f = fit.load_fit(paths.processed)
    tables = []
    mvn, feas, retry_t = {}, {}, pd.DataFrame()
    for n in PREDICTION:
        pp = paths.processed / f"predictions_{n}.csv"
        if not pp.exists() or not (paths.raw / n).exists():
            continue
        pred = pd.read_csv(pp)
        steps, runs = fit.load_experiments([n], paths.raw)
        if runs.empty:
            continue
        tables.append(agreement.l3_cell_table(pred, runs))
        if n == "E4_reliability_pred":
            mvn = agreement.markov_vs_naive(pred, runs)
        if n == "E7_retry" and not steps.empty:
            retry_t = agreement.retry_ceiling(steps, runs)
            retry_t.to_csv(paths.processed / "retry_table.csv", index=False)
        if n == "E9_feasibility":
            feas = agreement.feasibility_accuracy(pred, runs, load_config(n)["constraints"])
            if feas:
                feas.pop("table").to_csv(paths.processed / "e9_table.csv", index=False)
    cell_t = pd.concat(tables, ignore_index=True) if tables else pd.DataFrame()
    cell_t.to_csv(paths.processed / "agreement_l3_cells.csv", index=False)
    lat = agreement.latency_fit(cell_t[cell_t["arm"] != "single_shot"]) if not cell_t.empty else {}
    checks = agreement.summarize_checks(cell_t, mvn, retry_t, feas, lat)

    P = f.params_for(10, 1000).with_(max_steps=30)
    cfgs = [(P, "naive"), (P, "cached"), (P.with_(summ_every=5), "summarized"),
            (P.with_(depth=20, max_steps=60, f_inject=0.2, d_detect=0.5, retries=3), "naive")]
    l12 = agreement.l1_l2_table(cfgs, n_runs=l2_runs)
    l12.to_csv(paths.processed / "agreement_l1_l2.csv", index=False)
    rmc = [agreement.retry_delivery_mc(0.2, d, R, n=100_000, seed=i) for i, (d, R) in
           enumerate([(0.2, 0), (0.5, 3), (0.9, 6)])]
    checks["l1_l2"] = {"pass": bool(l12["pass"].all()), "n_checks": int(len(l12)),
                       "retry_closed_form_pass": bool(all(r["pass"] for r in rmc))}
    if mvn:
        checks["markov_vs_naive"].update({k: v for k, v in mvn.items()})
    agreement.write_report(checks, paths.processed)
    for k, c in checks.items():
        status = {True: "PASS", False: "FAIL", None: "report"}[c.get("pass")]
        print(f"  {k:16s} {status:6s} value={c.get('value', '')}")
    return checks


def figures(paths: Paths, out: Path | None = None, tables_out: Path | None = None):
    from loopbounds.figures import make_all

    if out is None:
        out = (paths.processed.parent / "figures") if paths.local else REPO_ROOT / "paper" / "figures"
    if tables_out is None and paths.local:
        tables_out = paths.processed.parent / "tables"
    made = make_all(paths.processed, out, tables_out)
    print(f"{len(made)} files -> {out}")
    return made


def mock_pipeline(*, scale: float = 0.3, l2_runs: int = 20_000, n_sim: int = 5000, verbose: bool = False):
    """Every stage, offline, with mock clients (data/mock/)."""
    paths = Paths.make(mock=True)
    print("== validate (E0)"); v = validate(paths, runs=max(200, int(1000 * scale)))  # noqa: E702
    print(json.dumps({k: v[k] for k in ("p", "r", "e")}, default=float))
    print("== calibrate"); calibrate(paths, scale=scale, verbose=verbose)  # noqa: E702
    print("== predict"); predict_stage(paths, post_hoc=False, n_sim=n_sim)  # noqa: E702
    print("== run-predict"); run_predict(paths, scale=scale, verbose=verbose)  # noqa: E702
    print("== external (E10)"); external(paths)  # noqa: E702
    print("== analyze"); checks = analyze(paths, l2_runs=l2_runs)  # noqa: E702
    print("== figures"); figures(paths)  # noqa: E702
    return checks


def local_pipeline(model: str, *, provider: str = "ollama", scale: float = 0.2, num_ctx: int = 32768,
                   n_sim: int = 5000, l2_runs: int = 20_000, external_tasks: bool = True,
                   budget_usd: float | None = None, verbose: bool = False) -> dict:
    """Calibrate -> predict -> prediction runs -> E10 -> analyze -> figures for one local model.

    Exploratory study: predictions are still written before the model's prediction-phase
    data exists (the predict step refuses otherwise), but no git tag is required.
    """
    if provider == "openai":
        paths = Paths.make(openai=model, budget_usd=budget_usd)
    else:
        paths = Paths.make(ollama=model, num_ctx=num_ctx)
    print(f"== [{model}] calibrate"); calibrate(paths, scale=scale, verbose=verbose)  # noqa: E702
    print(f"== [{model}] predict"); predict_stage(paths, n_sim=n_sim)  # noqa: E702
    print(f"== [{model}] run-predict"); run_predict(paths, scale=scale, verbose=verbose)  # noqa: E702
    if external_tasks:
        print(f"== [{model}] external"); external(paths, verbose=verbose)  # noqa: E702
    print(f"== [{model}] analyze"); checks = analyze(paths, l2_runs=l2_runs)  # noqa: E702
    print(f"== [{model}] figures"); figures(paths)  # noqa: E702
    return checks


