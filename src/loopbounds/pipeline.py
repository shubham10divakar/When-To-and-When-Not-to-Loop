"""End-to-end pipeline stages (design doc §6 ordering, §10 Makefile targets).

    E0 → E0b → calibration (E1, E2, E3, E5, E8a) → fit
       → predict (writes predictions + E9 cells) → freeze PREREG.md, tag prereg-v1
       → prediction runs (E4, E6, E7, E8b, E9) → E10 → analyze → figures

``mock=True`` swaps every real client for a mock with known ground truth
(``configs/mock_truth.yaml``) and writes to ``data/mock/`` so the entire
pipeline runs offline without touching real data.
"""

from __future__ import annotations

import json
import subprocess
from dataclasses import dataclass
from pathlib import Path

import pandas as pd
import yaml

from loopbounds.analysis import agreement, fit, predict
from loopbounds.harness.budget import BudgetExceeded
from loopbounds.harness.runner import load_config, run_experiment
from loopbounds.params import CONFIG_DIR, REPO_ROOT

CALIBRATION = ["E1_cost", "E2_context_wall", "E3_reliability_cal", "E5_coupling", "E8a_single_shot_cal"]
PREDICTION = ["E4_reliability_pred", "E6_summarization", "E7_retry", "E8b_single_shot_pred", "E9_feasibility"]
EXTERNAL = "E10_coding"
PREREG_TAG = "prereg-v1"


@dataclass(frozen=True)
class Paths:
    raw: Path
    processed: Path
    mock: bool = False
    provider: str | None = None        # "ollama" | "openai" for a per-model study
    model: str | None = None           # e.g. "llama3.1:8b", "gpt-4.1-nano"
    num_ctx: int = 32768               # Ollama only
    budget_usd: float | None = None    # study-wide spend cap (paid providers)

    @classmethod
    def make(cls, mock: bool = False, ollama: str | None = None, num_ctx: int = 32768,
             openai: str | None = None, budget_usd: float | None = None) -> "Paths":
        provider, model = ("ollama", ollama) if ollama else (("openai", openai) if openai else (None, None))
        if provider:
            root = REPO_ROOT / "data" / provider / model_slug(model)
        else:
            root = REPO_ROOT / "data" / ("mock" if mock else "")
        p = cls(root / "raw", root / "processed", mock, provider, model, num_ctx, budget_usd)
        p.raw.mkdir(parents=True, exist_ok=True)
        p.processed.mkdir(parents=True, exist_ok=True)
        if mock:
            (p.processed / "MOCK").write_text("Generated by mock clients; not real measurements.\n")
        if provider:
            extra = f" num_ctx={num_ctx}" if provider == "ollama" else ""
            (p.processed / "MODEL").write_text(f"{provider}/{model}{extra}\n")
        return p

    @property
    def ollama(self) -> str | None:
        return self.model if self.provider == "ollama" else None

    @property
    def local(self) -> bool:
        """Separate study directory (mock or per-model study): predictions live next to its data."""
        return self.mock or bool(self.provider)

    def client_spec(self, seed: int = 0) -> dict | None:
        if self.provider == "ollama":
            return {"kind": "ollama", "model": self.model, "num_ctx": self.num_ctx, "seed": seed}
        if self.provider == "openai":
            return {"kind": "openai", "model": self.model, "seed": seed}
        return None

    def spent_usd(self) -> float:
        """Total actual spend recorded in this study's run logs."""
        tot = 0.0
        for f in self.raw.rglob("*.jsonl"):
            try:
                last = f.read_text(encoding="utf-8").rstrip().rsplit("\n", 1)[-1]
                tot += float(json.loads(last).get("cost_usd", 0.0))
            except (ValueError, OSError):
                continue
        return tot

    @property
    def e9_cells(self) -> Path:
        return (self.processed if self.local else CONFIG_DIR / "experiments") / "E9_cells.generated.yaml"


def model_slug(model: str) -> str:
    return model.replace(":", "-").replace("/", "_")


def mock_truth() -> dict:
    return yaml.safe_load((CONFIG_DIR / "mock_truth.yaml").read_text())


def mockify(cfg: dict) -> dict:
    t = mock_truth()
    cfg = dict(cfg)
    cfg["client"] = {"kind": "coupled_mock", **{k: t[k] for k in ("p0", "lam", "form", "r", "e", "a_out", "ttft_a0",
                                                                  "ttft_a1", "ttft_a2", "tps", "gamma", "ss_b0",
                                                                  "ss_b1", "ss_b2", "seed")}}
    return cfg


def _cfg(name: str, paths: Paths, scale: float | None = None) -> dict:
    cfg = load_config(name)
    if paths.mock:
        cfg = mockify(cfg)
    elif paths.provider:
        cfg = {**cfg, "client": paths.client_spec(int(cfg.get("seed", 0)))}
        if paths.provider == "ollama" and cfg.get("window_cap"):
            cfg["window_cap"] = min(int(cfg["window_cap"]), int(0.85 * paths.num_ctx))
    if paths.budget_usd is not None:
        remaining = max(0.0, paths.budget_usd - paths.spent_usd())
        cfg["max_spend_usd"] = min(float(cfg.get("max_spend_usd") or remaining), remaining)
    if scale is not None and "runs_per_cell" in cfg:
        cfg["runs_per_cell"] = max(3, int(round(cfg["runs_per_cell"] * scale)))
    if cfg.get("cells_file"):
        cfg["cells_file"] = str(paths.e9_cells)
    return cfg


def run(names: list[str], paths: Paths, *, scale: float | None = None, verbose: bool = False) -> list:
    out = []
    for n in names:
        if n == EXTERNAL:
            out.append(external(paths, verbose=verbose))
            continue
        try:
            s = run_experiment(_cfg(n, paths, scale), out_root=paths.raw, verbose=verbose)
        except BudgetExceeded as exc:       # pre-run L1 estimate above the remaining budget
            print(f"{n}: SKIPPED - {exc}")
            continue
        print(f"{s.name}: {s.n_runs} runs ({s.n_skipped} skipped), spent ${s.spent_usd:.4f}, "
              f"L1 estimate ${s.estimate_usd:.4f}{'  ABORTED' if s.aborted else ''}")
        out.append(s)
    return out


def estimate(names: list[str], paths: Paths) -> dict[str, float]:
    out = {}
    for n in names:
        if n == EXTERNAL:
            continue
        try:
            out[n] = run_experiment(_cfg(n, paths), out_root=paths.raw, dry_run=True).estimate_usd
        except FileNotFoundError:   # E9 cells are generated by `predict`
            out[n] = float("nan")
    return out


